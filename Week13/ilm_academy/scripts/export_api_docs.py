"""Writes docs/api.md and docs/openapi.json from the FastAPI app itself, so the API docs cannot
drift from the code. Re-run after changing an endpoint:

    python scripts/export_api_docs.py

The role of each endpoint is read from its dependency (require("student") / require("teacher") /
current_user), not typed by hand.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fastapi.routing import APIRoute  # noqa: E402

from ilm.api import auth  # noqa: E402
from ilm.api.main import app  # noqa: E402

GROUPS = [("Auth", ("/api/auth", "/api/me", "/api/health")),
          ("Student", ("/api/me/path", "/api/exercises", "/api/submissions", "/api/practice", "/api/answers")),
          ("Tutor", ("/api/tutor/ask", "/api/tutor/hint")),
          ("Teacher", ("/api/class", "/api/review", "/api/questions", "/api/tutor/safety", "/api/impact"))]

ERRORS = """| status | when | body |
|---|---|---|
| 401 | not logged in, or the session ended (8 hours) | `{"detail": "Please log in."}` |
| 403 | logged in with the wrong role (a student calling a teacher endpoint) | `{"detail": "This page is for teachers."}` |
| 404 | unknown exercise, submission, question or review item; another student's submission | `{"detail": "No such ..."}` |
| 422 | invalid body (too long, missing field, unknown decision) | FastAPI validation detail |
| 429 | per-student limit: 12 code runs a minute; tutor 8 a minute and 80 a day | `{"detail": "..."}` |
| 503 | tutor unavailable (no API key, or the free model quota is used up) | `{"detail": "..."}` |"""


def role_of(route: APIRoute) -> str:
    for dep in route.dependant.dependencies:
        call = dep.call
        if call is auth.current_user:
            return "any logged-in user"
        for cell in getattr(call, "__closure__", None) or ():
            if cell.cell_contents in ("student", "teacher"):
                return cell.cell_contents
    return "public"


def fields(schema_ref: dict, spec: dict) -> str:
    name = schema_ref.get("$ref", "").rsplit("/", 1)[-1]
    s = spec["components"]["schemas"].get(name, {})
    req = set(s.get("required", []))
    out = []
    for k, v in s.get("properties", {}).items():
        t = v.get("type") or "/".join(a.get("type", "?") for a in v.get("anyOf", []))
        lim = [f"{a} {v[b]}" for a, b in (("max", "maxLength"), ("min", "minLength"), ("≥", "minimum"),
                                         ("≤", "maximum"), ("pattern", "pattern")) if b in v]
        out.append(f"`{k}` {t}{'' if k in req else ' (optional)'}" + (f" [{', '.join(lim)}]" if lim else ""))
    return "; ".join(out)


def main() -> None:
    spec = app.openapi()
    routes = [r for r in app.routes if isinstance(r, APIRoute) and r.path.startswith("/api")]
    lines = ["# API reference", "",
             "Generated by `python scripts/export_api_docs.py` from the running FastAPI app "
             "(`ilm/api/main.py`); the machine-readable version is [openapi.json](openapi.json), and a "
             "live, clickable version is at `/api/docs` on any running server.", "",
             "**Auth.** `POST /api/auth/login` sets an httpOnly cookie `ilm_session` (a signed JWT, 8 hours, "
             "SameSite=Lax, Secure in production). Every other call sends it automatically from the browser. "
             "From a script, send it as a `Cookie` header (see `ilm/api/loadtest.py`).", "",
             "**Hidden tests never leave the server.** Exercise pages carry visible tests only; a submission "
             "result says how many hidden tests failed and in what way (wrong value, error, too slow), never "
             "their input or answer (`service.public_result` is a whitelist).", ""]
    seen = set()
    for title, prefixes in GROUPS:
        lines += [f"## {title}", "", "| method | path | who | what | body |", "|---|---|---|---|---|"]
        for r in routes:
            key = (r.path, tuple(sorted(r.methods)))
            if key in seen or not r.path.startswith(prefixes) or (title == "Auth" and r.path == "/api/me/path"):
                continue
            seen.add(key)
            for m in sorted(r.methods):
                op = spec["paths"][r.path][m.lower()]
                body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
                params = [p["name"] + (" (query)" if p["in"] == "query" else "") for p in op.get("parameters", [])]
                doc = (r.endpoint.__doc__ or "").strip().split("\n")[0] or r.name.replace("_", " ")
                desc = fields(body, spec) if body else (", ".join(params) if params else "")
                lines.append(f"| {m} | `{r.path}` | {role_of(r)} | {doc} | {desc} |")
        lines.append("")
    lines += ["## Errors", "", ERRORS, ""]
    docs = ROOT / "docs"
    (docs / "api.md").write_text("\n".join(lines), encoding="utf-8")
    (docs / "openapi.json").write_text(json.dumps(spec, indent=1), encoding="utf-8")
    print(f"{len(routes)} routes -> docs/api.md, docs/openapi.json")


if __name__ == "__main__":
    main()
