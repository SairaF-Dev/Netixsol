"""
Weekly management insight report (brief Day 4 Task 5): numbers computed with SQL / pandas, prose written by the LLM
(Gemini, if LLM_API_KEY is set). Any number in the LLM text that is not in the computed facts rejects the LLM text
and the deterministic template is used instead.

Writes reports/weekly_insight_report.md and reports/weekly_insight_facts.json.
Schedule: weekly (see docs/monitoring_and_retraining.md).
"""

from __future__ import annotations

import json

import duckdb

from shopkaro.config.settings import settings
from shopkaro.reviews.insights_report import weekly_facts, write_weekly_report
from shopkaro.reviews.intelligence import ReviewIntelligencePipeline


def main() -> None:
    pipeline = ReviewIntelligencePipeline()
    con = duckdb.connect(str(settings.duckdb_path), read_only=True)
    reviews = con.execute("SELECT * FROM reviews").df()
    predicted = pipeline.predict_review_labels(reviews)
    facts = weekly_facts(con, predicted)
    con.close()

    report, engine = write_weekly_report(facts)
    header = f"<!-- generated by scripts/run_weekly_insight_report.py; prose engine: {engine}; numbers: weekly_insight_facts.json -->\n"
    (settings.reports_dir / "weekly_insight_report.md").write_text(header + report, encoding="utf-8")
    (settings.reports_dir / "weekly_insight_facts.json").write_text(json.dumps(facts, indent=2, default=str), encoding="utf-8")
    print(f"engine: {engine}\n")
    print(report)


if __name__ == "__main__":
    main()
